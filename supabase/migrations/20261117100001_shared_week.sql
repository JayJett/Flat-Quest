-- Phase 10 — The shared week: per-flat time zones and shared appointments with optional coverage.
--
-- Additive. No existing row is modified. Existing flats without a valid time zone keep
-- behaving as Pacific/Auckland. Recovery: supabase/rollback/20261117100001_shared_week_down.sql.

-- ───────────────────────── 1. One validated time zone per flat ─────────────────────────
-- A flat's calendar day and week, and reminder timing, follow its IANA time zone. Before
-- Phase 10 any owner could store free text in settings.timezone, and one invalid value made the
-- hourly reminder job fail for every flat. Validation now happens on write, and readers use a
-- helper that can never fail.
create function private.valid_time_zone(p_zone text) returns boolean
language sql stable set search_path = '' as $$
  select p_zone is not null and char_length(p_zone) <= 64
     and exists (select 1 from pg_catalog.pg_timezone_names where name = p_zone)
$$;

create function private.household_zone(p_settings jsonb) returns text
language sql stable set search_path = '' as $$
  select case when private.valid_time_zone(p_settings->>'timezone') then p_settings->>'timezone' else 'Pacific/Auckland' end
$$;

create function private.households_settings_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if jsonb_typeof(new.settings) is distinct from 'object' then
    raise exception 'Household settings must be an object' using errcode = '22023';
  end if;
  if new.settings ? 'timezone' and (tg_op = 'INSERT' or new.settings->'timezone' is distinct from old.settings->'timezone')
     and not private.valid_time_zone(new.settings->>'timezone') then
    raise exception 'Choose a time zone from the list' using errcode = '22023';
  end if;
  return new;
end $$;
create trigger households_settings_guard before insert or update of settings on public.households
  for each row execute function private.households_settings_guard();

-- Owners set the zone without rewriting (and racing) the rest of the settings object.
create function public.set_household_timezone(p_household uuid, p_zone text) returns text
language plpgsql security definer set search_path = '' as $$
begin
  if not private.is_household_owner(p_household) then
    raise exception 'Only the person who set up the flat can change its time zone' using errcode = '42501';
  end if;
  if not private.valid_time_zone(p_zone) then
    raise exception 'Choose a time zone from the list' using errcode = '22023';
  end if;
  update public.households set settings = settings || jsonb_build_object('timezone', p_zone) where id = p_household;
  return p_zone;
end $$;
revoke all on function public.set_household_timezone(uuid, text) from public, anon;
grant execute on function public.set_household_timezone(uuid, text) to authenticated;

-- ───────────────────────── 2. Shared appointments ─────────────────────────
-- An inspection, a meter reading, a furniture pickup arranged with a seller. Optionally someone
-- needs to be home: one flatmate volunteers ("host"). Tasks and purchases stay in their own
-- tables; the calendar only projects them.
create table public.calendar_appointments (
  -- Generated by the client per draft, so a retry after an unclear response can't duplicate.
  id uuid primary key,
  household_id uuid not null references public.households(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 80 and title = btrim(title)),
  notes text check (char_length(notes) between 1 and 500),
  room_id uuid,
  all_day boolean not null,
  -- All-day: the civil date ("Friday" everywhere). Timed: the flat-local date when it was saved;
  -- the actual moment is starts_at/ends_at, which a later time-zone change never moves.
  scheduled_on date not null check (scheduled_on between date '2000-01-01' and date '2100-12-31'),
  starts_at timestamptz,
  ends_at timestamptz,
  needs_cover boolean not null default false,
  host_id uuid,
  created_by uuid references auth.users(id) on delete set null,
  cancelled_at timestamptz,
  cancelled_by uuid references auth.users(id) on delete set null,
  revision integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, household_id),
  check ((all_day and starts_at is null and ends_at is null)
      or (not all_day and starts_at is not null and ends_at > starts_at and ends_at - starts_at <= interval '24 hours')),
  check (host_id is null or (needs_cover and cancelled_at is null)),
  check (cancelled_by is null or cancelled_at is not null),
  -- A deleted room leaves the appointment; a departing host reopens coverage.
  foreign key (room_id, household_id) references public.rooms(id, household_id) on delete set null (room_id),
  foreign key (household_id, host_id) references public.household_members(household_id, user_id) on delete set null (host_id)
);
create index calendar_appointments_week_idx on public.calendar_appointments (household_id, scheduled_on) where cancelled_at is null;
create index calendar_appointments_room_idx on public.calendar_appointments (room_id) where room_id is not null;
create index calendar_appointments_host_idx on public.calendar_appointments (household_id, host_id) where host_id is not null;
create index calendar_appointments_created_by_idx on public.calendar_appointments (created_by);
create index calendar_appointments_cancelled_by_idx on public.calendar_appointments (cancelled_by);

alter table public.calendar_appointments enable row level security;
create policy "appointments: members read" on public.calendar_appointments
  for select to authenticated using (private.is_household_member(household_id));
-- Every write goes through the functions below, which enforce permissions, coverage and revisions.
revoke all on public.calendar_appointments from anon, authenticated;
grant select on public.calendar_appointments to authenticated;

-- Every effective change (including the database clearing a room or host) bumps the revision,
-- so a stale screen can never overwrite or claim a slot it hasn't seen.
create function private.appointments_revision() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new is distinct from old then
    new.revision := old.revision + 1;
    new.updated_at := clock_timestamp();
  end if;
  return new;
end $$;
revoke all on function private.appointments_revision() from public, anon, authenticated;
create trigger calendar_appointments_revision before update on public.calendar_appointments
  for each row execute function private.appointments_revision();

-- Resolves a flat-local date and time to an instant, refusing times that don't exist (clocks
-- go forward) or happen twice (clocks go back) so nobody is booked for the wrong hour.
create function private.local_instant(p_date date, p_time time, p_zone text) returns timestamptz
language plpgsql stable set search_path = '' as $$
declare
  v_local timestamp := p_date + p_time;
  v_at timestamptz := v_local at time zone p_zone;
  v_shift interval;
begin
  if (v_at at time zone p_zone) <> v_local then
    raise exception '% doesn’t exist on % in % (the clocks change). Choose another time.', to_char(p_time, 'HH24:MI'), p_date, p_zone using errcode = '22008';
  end if;
  foreach v_shift in array array[interval '30 minutes', interval '1 hour', interval '2 hours'] loop
    if ((v_at - v_shift) at time zone p_zone) = v_local or ((v_at + v_shift) at time zone p_zone) = v_local then
      raise exception '% happens twice on % in % (the clocks change). Choose another time.', to_char(p_time, 'HH24:MI'), p_date, p_zone using errcode = '22008';
    end if;
  end loop;
  return v_at;
end $$;
revoke all on function private.local_instant(date, time, text) from public, anon, authenticated;

create function private.appointment_json(a public.calendar_appointments) returns jsonb
language sql stable set search_path = '' as $$ select to_jsonb(a) $$;
revoke all on function private.appointment_json(public.calendar_appointments) from public, anon, authenticated;

-- Create (p_expected_revision null) or edit. Changing the day or time slot, or no longer needing
-- someone home, clears the volunteer in the same statement. Title, notes and room keep it.
create function public.save_appointment(
  p_id uuid, p_household uuid, p_expected_revision integer,
  p_title text, p_notes text, p_room uuid,
  p_date date, p_start time, p_end time, p_needs_cover boolean
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_row public.calendar_appointments%rowtype;
  v_zone text;
  v_start timestamptz;
  v_end timestamptz;
  v_all_day boolean := p_start is null and p_end is null;
  v_title text := btrim(coalesce(p_title, ''));
  v_notes text := nullif(btrim(coalesce(p_notes, '')), '');
  v_moved boolean;
begin
  if v_uid is null or not private.user_in_household_unchecked(v_uid, p_household) then
    raise exception 'You’re not a member of this flat' using errcode = '42501';
  end if;
  if char_length(v_title) not between 1 and 80 then
    raise exception 'Give it a short title (up to 80 characters)' using errcode = '23514';
  end if;
  if char_length(v_notes) > 500 then
    raise exception 'Keep notes under 500 characters' using errcode = '23514';
  end if;
  if p_date is null then
    raise exception 'Choose a day' using errcode = '23514';
  end if;
  if (p_start is null) <> (p_end is null) then
    raise exception 'Give both a start and an end time, or make it all day' using errcode = '23514';
  end if;
  if p_room is not null and not exists (select 1 from public.rooms where id = p_room and household_id = p_household) then
    raise exception 'That room isn’t in this flat' using errcode = '23514';
  end if;
  select private.household_zone(settings) into v_zone from public.households where id = p_household for share;
  if not v_all_day then
    if p_end <= p_start then
      raise exception 'The end time must be after the start, on the same day' using errcode = '23514';
    end if;
    v_start := private.local_instant(p_date, p_start, v_zone);
    v_end := private.local_instant(p_date, p_end, v_zone);
  end if;

  if p_expected_revision is null then
    insert into public.calendar_appointments (id, household_id, title, notes, room_id, all_day, scheduled_on, starts_at, ends_at, needs_cover, created_by)
    values (p_id, p_household, v_title, v_notes, p_room, v_all_day, p_date, v_start, v_end, coalesce(p_needs_cover, false), v_uid)
    on conflict (id) do nothing
    returning * into v_row;
    if not found then
      -- A retry of a create that already succeeded returns the original, never a duplicate.
      select * into v_row from public.calendar_appointments where id = p_id;
      if v_row.household_id is distinct from p_household or v_row.created_by is distinct from v_uid then
        raise exception 'That appointment can’t be created' using errcode = '23505';
      end if;
    end if;
    return private.appointment_json(v_row);
  end if;

  select * into v_row from public.calendar_appointments where id = p_id and household_id = p_household for update;
  if not found or v_row.cancelled_at is not null then
    raise exception 'That appointment was cancelled or removed' using errcode = 'P0002';
  end if;
  if v_row.created_by is distinct from v_uid and not private.is_household_owner(p_household) then
    raise exception 'Only the person who added it, or the flat’s owner, can change it' using errcode = '42501';
  end if;
  if v_row.revision <> p_expected_revision then
    raise exception 'Someone changed this appointment while you were editing' using errcode = 'FQ409';
  end if;
  v_moved := v_row.all_day <> v_all_day or v_row.starts_at is distinct from v_start or v_row.ends_at is distinct from v_end
          or (v_all_day and v_row.scheduled_on <> p_date) or not coalesce(p_needs_cover, false);
  update public.calendar_appointments
     set title = v_title, notes = v_notes, room_id = p_room, all_day = v_all_day, scheduled_on = p_date,
         starts_at = v_start, ends_at = v_end, needs_cover = coalesce(p_needs_cover, false),
         host_id = case when v_moved then null else host_id end
   where id = p_id
  returning * into v_row;
  return private.appointment_json(v_row);
end $$;
revoke all on function public.save_appointment(uuid, uuid, integer, text, text, uuid, date, time, time, boolean) from public, anon;
grant execute on function public.save_appointment(uuid, uuid, integer, text, text, uuid, date, time, time, boolean) to authenticated;

-- Volunteer to be home ('claim') or step back ('release'). Exactly one person can hold a slot;
-- a claim made against an older version (e.g. before it moved) is refused.
create function public.set_appointment_cover(p_id uuid, p_expected_revision integer, p_action text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_row public.calendar_appointments%rowtype;
begin
  select * into v_row from public.calendar_appointments where id = p_id for update;
  if not found or v_uid is null or not private.user_in_household_unchecked(v_uid, v_row.household_id) then
    raise exception 'That appointment isn’t available' using errcode = 'P0002';
  end if;
  if v_row.cancelled_at is not null then
    raise exception 'That appointment was cancelled' using errcode = 'P0002';
  end if;
  if p_action = 'claim' then
    if v_row.host_id = v_uid then return private.appointment_json(v_row); end if;
    if v_row.revision <> p_expected_revision then
      raise exception 'This appointment changed. Check the new time before volunteering.' using errcode = 'FQ409';
    end if;
    if not v_row.needs_cover then
      raise exception 'Nobody needs to be home for this any more' using errcode = 'FQ409';
    end if;
    if v_row.host_id is not null then
      raise exception '% is already going to be home', private.display_name(v_row.host_id) using errcode = 'FQ409';
    end if;
    update public.calendar_appointments set host_id = v_uid where id = p_id returning * into v_row;
  elsif p_action = 'release' then
    if v_row.host_id is distinct from v_uid then
      if v_row.host_id is null then return private.appointment_json(v_row); end if;
      raise exception 'Only the person covering this can step back' using errcode = '42501';
    end if;
    update public.calendar_appointments set host_id = null where id = p_id returning * into v_row;
  else
    raise exception 'Unknown action' using errcode = '22023';
  end if;
  return private.appointment_json(v_row);
end $$;
revoke all on function public.set_appointment_cover(uuid, integer, text) from public, anon;
grant execute on function public.set_appointment_cover(uuid, integer, text) to authenticated;

-- Cancelling is a recorded state change (it leaves the agenda but stays in history).
create function public.cancel_appointment(p_id uuid, p_expected_revision integer) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_row public.calendar_appointments%rowtype;
begin
  select * into v_row from public.calendar_appointments where id = p_id for update;
  if not found or v_uid is null or not private.user_in_household_unchecked(v_uid, v_row.household_id) then
    raise exception 'That appointment isn’t available' using errcode = 'P0002';
  end if;
  if v_row.cancelled_at is not null then return private.appointment_json(v_row); end if;
  if v_row.created_by is distinct from v_uid and not private.is_household_owner(v_row.household_id) then
    raise exception 'Only the person who added it, or the flat’s owner, can cancel it' using errcode = '42501';
  end if;
  if v_row.revision <> p_expected_revision then
    raise exception 'Someone changed this appointment. Check it before cancelling.' using errcode = 'FQ409';
  end if;
  update public.calendar_appointments set cancelled_at = now(), cancelled_by = v_uid, host_id = null
   where id = p_id returning * into v_row;
  return private.appointment_json(v_row);
end $$;
revoke all on function public.cancel_appointment(uuid, integer) from public, anon;
grant execute on function public.cancel_appointment(uuid, integer) to authenticated;

